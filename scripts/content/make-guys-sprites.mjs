#!/usr/bin/env node
// Cuts the little ink figures out of public/guys.webp — a photograph of a
// painted sheet — and packs them into the sprite sheet interface.exe draws
// instead of dots when you switch its nodes over to Guys.
//
//   node scripts/content/make-guys-sprites.mjs [--debug]
//
// Writes public/guys/guys.webp (the sheet) and src/data/guys.json (how to read
// it). Both are committed: the source photograph is 800KB and lit unevenly, so
// the cutting is done once here rather than in everyone's browser. Re-run it
// only if the photograph changes. --debug also writes a contact sheet to the
// scratchpad so the cut-outs can be eyeballed.

import sharp from "sharp";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const SOURCE = "public/guys.webp";
const SHEET_OUT = "public/guys/guys.webp";
const MANIFEST_OUT = "src/data/guys.json";

// The photograph has a second sheet down the left edge and a cloth across the
// bottom corner; this is the paper itself, in source pixels.
const CROP = { left: 200, top: 110, width: 2660, height: 3560 };
// Everything downstream works on this width — figures land around 60px tall,
// which is plenty for sprites drawn at a third of that.
const WORK_WIDTH = 1100;
// How much darker than the paper around it a pixel has to be to count as ink.
const INK = 26;
const PAD = 4;
// The sheet is packed at working resolution and shipped at half of it: the
// canvas draws a guy around 30px tall, so anything sharper is bytes nobody
// sees.
const SHIP_SCALE = 0.5;

const args = new Set(process.argv.slice(2));
const debug = args.has("--debug");

async function main() {
  const base = sharp(SOURCE).rotate().extract(CROP).resize({ width: WORK_WIDTH }).greyscale();
  const { data: grey, info } = await base.clone().raw().toBuffer({ resolveWithObject: true });
  const { width, height } = info;

  // The paper is lit unevenly — brighter top right than bottom left — so "ink"
  // is judged against the local paper tone rather than one global threshold.
  const { data: paper } = await base.clone().blur(24).raw().toBuffer({ resolveWithObject: true });

  const ink = new Uint8Array(width * height);
  for (let i = 0; i < ink.length; i += 1) {
    ink[i] = paper[i] - grey[i] > INK ? 1 : 0;
  }

  // A figure is a handful of separate brush strokes — head clear of the body,
  // legs clear of both — so labelling the ink as it stands cuts every guy into
  // pieces. Fattening the mask first closes those gaps without closing the much
  // wider ones between neighbours; the cut-out still uses the original ink.
  const merged = dilate(ink, width, height, 4);
  const blobs = label(merged, width, height);
  const figures = pickFigures(blobs, width, height);
  if (figures.length === 0) throw new Error("no figures found — check CROP and INK");

  // One cell per figure, all the same size, each figure centred in its cell so
  // the canvas can draw any of them from its middle.
  // Even, so halving the sheet lands cells on whole pixels.
  const even = (n) => n + (n % 2);
  const cellW = even(Math.max(...figures.map((f) => f.w)) + PAD * 2);
  const cellH = even(Math.max(...figures.map((f) => f.h)) + PAD * 2);
  const cols = Math.ceil(Math.sqrt(figures.length));
  const rows = Math.ceil(figures.length / cols);

  const sheet = Buffer.alloc(cellW * cols * cellH * rows * 4);
  const sheetW = cellW * cols;

  figures.forEach((figure, index) => {
    const cx = (index % cols) * cellW + Math.round((cellW - figure.w) / 2);
    const cy = Math.floor(index / cols) * cellH + Math.round((cellH - figure.h) / 2);
    for (let y = 0; y < figure.h; y += 1) {
      for (let x = 0; x < figure.w; x += 1) {
        const src = (figure.y + y) * width + (figure.x + x);
        // Only this figure's own pixels: a neighbour leaning into the same box
        // stays behind.
        if (blobs.ids[src] !== figure.id) continue;
        // Alpha carries the brush texture — these are painted, not printed, and
        // a hard cut-out loses the dry-brush edges.
        const darkness = Math.max(0, Math.min(255, Math.round(((paper[src] - grey[src]) / 120) * 255)));
        if (darkness < 12) continue;
        const dst = ((cy + y) * sheetW + (cx + x)) * 4;
        sheet[dst] = 12;
        sheet[dst + 1] = 12;
        sheet[dst + 2] = 16;
        sheet[dst + 3] = darkness;
      }
    }
  });

  await mkdir(path.dirname(SHEET_OUT), { recursive: true });
  const shipW = Math.round(sheetW * SHIP_SCALE);
  const shipH = Math.round(cellH * rows * SHIP_SCALE);
  await sharp(sheet, { raw: { width: sheetW, height: cellH * rows, channels: 4 } })
    .resize({ width: shipW, height: shipH })
    .webp({ quality: 82, alphaQuality: 86 })
    .toFile(SHEET_OUT);

  const manifest = {
    note: "Generated by scripts/content/make-guys-sprites.mjs from public/guys.webp — do not hand-edit.",
    sheet: "/guys/guys.webp",
    cellWidth: Math.round(cellW * SHIP_SCALE),
    cellHeight: Math.round(cellH * SHIP_SCALE),
    columns: cols,
    count: figures.length,
    // Where the ink actually sits inside its cell, [x, y, w, h] in shipped
    // pixels. Cells are all the size of the biggest figure and each guy is
    // centred in his own, so a short one is adrift in a lot of nothing —
    // anything that has to stand him on a line (the Party portrait does)
    // needs to know where his feet are.
    cells: figures.map((f) => [
      Math.round(Math.round((cellW - f.w) / 2) * SHIP_SCALE),
      Math.round(Math.round((cellH - f.h) / 2) * SHIP_SCALE),
      Math.round(f.w * SHIP_SCALE),
      Math.round(f.h * SHIP_SCALE),
    ]),
  };
  // One cell per line — 76 four-number arrays exploded over 456 lines is not a
  // file anybody wants to scroll past.
  const json = JSON.stringify(manifest, null, 2).replace(
    /\[\s+(\d+),\s+(\d+),\s+(\d+),\s+(\d+)\s+\]/g,
    "[$1, $2, $3, $4]",
  );
  await writeFile(MANIFEST_OUT, `${json}\n`);

  console.log(
    `${figures.length} guys → ${SHEET_OUT} (${shipW}×${shipH}, cell ${Math.round(cellW * SHIP_SCALE)}×${Math.round(cellH * SHIP_SCALE)})`,
  );

  if (debug) {
    const contact = process.env.DEBUG_OUT ?? "guys-contact.png";
    await sharp(SHEET_OUT)
      .flatten({ background: "#ffffff" })
      .png()
      .toFile(contact);
    console.log(`contact sheet → ${contact}`);
  }
}

/** Grows the mask by `r` pixels in each direction, one axis at a time. */
function dilate(mask, width, height, r) {
  const pass = new Uint8Array(mask.length);
  for (let y = 0; y < height; y += 1) {
    const row = y * width;
    for (let x = 0; x < width; x += 1) {
      if (mask[row + x] === 0) continue;
      const from = Math.max(0, x - r);
      const to = Math.min(width - 1, x + r);
      for (let nx = from; nx <= to; nx += 1) pass[row + nx] = 1;
    }
  }
  const out = new Uint8Array(mask.length);
  for (let y = 0; y < height; y += 1) {
    const row = y * width;
    for (let x = 0; x < width; x += 1) {
      if (pass[row + x] === 0) continue;
      const from = Math.max(0, y - r);
      const to = Math.min(height - 1, y + r);
      for (let ny = from; ny <= to; ny += 1) out[ny * width + x] = 1;
    }
  }
  return out;
}

/** Flood-fills the ink mask into numbered blobs, with each blob's bounding box. */
function label(ink, width, height) {
  const ids = new Int32Array(width * height).fill(-1);
  const boxes = [];
  const stack = new Int32Array(width * height);

  for (let start = 0; start < ink.length; start += 1) {
    if (ink[start] === 0 || ids[start] !== -1) continue;
    const id = boxes.length;
    let top = 0;
    stack[top++] = start;
    ids[start] = id;
    let minX = width;
    let minY = height;
    let maxX = 0;
    let maxY = 0;
    let area = 0;

    while (top > 0) {
      const p = stack[--top];
      const x = p % width;
      const y = (p - x) / width;
      area += 1;
      if (x < minX) minX = x;
      if (x > maxX) maxX = x;
      if (y < minY) minY = y;
      if (y > maxY) maxY = y;

      // Eight-way: a dry brush leaves strokes that only touch at the corners.
      for (let dy = -1; dy <= 1; dy += 1) {
        for (let dx = -1; dx <= 1; dx += 1) {
          const nx = x + dx;
          const ny = y + dy;
          if (nx < 0 || ny < 0 || nx >= width || ny >= height) continue;
          const n = ny * width + nx;
          if (ink[n] === 0 || ids[n] !== -1) continue;
          ids[n] = id;
          stack[top++] = n;
        }
      }
    }

    boxes.push({ id, x: minX, y: minY, w: maxX - minX + 1, h: maxY - minY + 1, area });
  }

  return { ids, boxes };
}

/**
 * Keeps the blobs that are actually one whole figure: about as tall as the
 * typical one, taller than wide, solid enough not to be a smudge, and clear of
 * the crop edges where a figure may be cut in half.
 */
function pickFigures({ boxes }, width, height) {
  const tall = boxes.filter((b) => b.h >= 12 && b.area >= 60);
  if (tall.length === 0) return [];
  const heights = tall.map((b) => b.h).sort((a, b) => a - b);
  const median = heights[Math.floor(heights.length / 2)];

  return tall
    .filter((b) => {
      if (b.x <= 1 || b.y <= 1 || b.x + b.w >= width - 1 || b.y + b.h >= height - 1) return false;
      if (b.h < median * 0.62 || b.h > median * 1.45) return false;
      if (b.w > b.h * 0.95) return false;
      // A figure fills a good part of its box; a stray splash or two strokes
      // that happen to touch do not.
      if (b.area < b.w * b.h * 0.22) return false;
      return true;
    })
    .sort((a, b) => b.area - a.area);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});

#!/usr/bin/env node
// Cuts the little ink figures out of the photographed sheets in public/ —
// guys.webp, guys2.webp — and packs them all into the one sprite sheet
// party.webp draws instead of dots when you switch its nodes over to Guys.
//
//   node scripts/content/make-guys-sprites.mjs [--debug]
//
// Writes public/guys/guys.webp (the sheet) and src/data/guys.json (how to read
// it). Both are committed: the photographs are the better part of a megabyte
// each and lit unevenly, so the cutting is done once here rather than in
// everyone's browser. Re-run it only when a photograph changes or another sheet
// is painted. --debug also writes a contact sheet to the scratchpad so the
// cut-outs can be eyeballed.

import sharp from "sharp";
import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const SHEET_OUT = "public/guys/guys.webp";
const MANIFEST_OUT = "src/data/guys.json";

// The sheets, and where the paper sits in each photograph, in source pixels.
// Every shot has something else in frame — the next sheet along, a cloth across
// a corner, the table around it all — and the paper is never quite square to the
// camera, so each crop is judged by eye and kept well inside the paper's edges.
// A figure the crop clips is dropped rather than shipped half-painted.
const SHEETS = [
  { file: "public/guys.webp", crop: { left: 200, top: 110, width: 2660, height: 3560 } },
  { file: "public/guys2.webp", crop: { left: 170, top: 280, width: 2680, height: 3500 } },
];
// Everything downstream works on this width — figures land around 60px tall,
// which is plenty for sprites drawn at a third of that.
const WORK_WIDTH = 1100;
// How much darker than the paper around it a pixel has to be to count as ink.
const INK = 26;
const PAD = 4;
// The sheet is packed at working resolution and shipped at half of it: the
// canvas draws a guy around 30px tall, so anything sharper is bytes nobody
// sees.
const SHIP_SCALE = 0.5;

const args = new Set(process.argv.slice(2));
const debug = args.has("--debug");

async function main() {
  // Every sheet is cut on its own — each photograph has its own lighting and
  // its own idea of how big a guy is — and the cut-outs are pooled afterwards.
  const cuts = [];
  for (const sheet of SHEETS) {
    const found = await cutSheet(sheet);
    if (found.length === 0) throw new Error(`no figures found in ${sheet.file} — check its crop and INK`);
    console.log(`${found.length} guys from ${sheet.file}`);
    cuts.push(...found);
  }

  // One cell per figure, all the same size, each figure centred in its cell so
  // the canvas can draw any of them from its middle.
  // Even, so halving the sheet lands cells on whole pixels.
  const even = (n) => n + (n % 2);
  const cellW = even(Math.max(...cuts.map((c) => c.w)) + PAD * 2);
  const cellH = even(Math.max(...cuts.map((c) => c.h)) + PAD * 2);
  const cols = Math.ceil(Math.sqrt(cuts.length));
  const rows = Math.ceil(cuts.length / cols);

  const sheet = Buffer.alloc(cellW * cols * cellH * rows * 4);
  const sheetW = cellW * cols;

  cuts.forEach((cut, index) => {
    const cx = (index % cols) * cellW + Math.round((cellW - cut.w) / 2);
    const cy = Math.floor(index / cols) * cellH + Math.round((cellH - cut.h) / 2);
    for (let y = 0; y < cut.h; y += 1) {
      const from = y * cut.w * 4;
      cut.pixels.copy(sheet, ((cy + y) * sheetW + cx) * 4, from, from + cut.w * 4);
    }
  });

  await mkdir(path.dirname(SHEET_OUT), { recursive: true });
  const shipW = Math.round(sheetW * SHIP_SCALE);
  const shipH = Math.round(cellH * rows * SHIP_SCALE);
  const shipped = await sharp(sheet, { raw: { width: sheetW, height: cellH * rows, channels: 4 } })
    .resize({ width: shipW, height: shipH })
    .webp({ quality: 82, alphaQuality: 86 })
    .toBuffer();
  await writeFile(SHEET_OUT, shipped);

  // The manifest is the only thing that says where a guy sits in the sheet, and
  // the two are read together — so a browser holding yesterday's sheet and
  // today's cell coordinates cuts figures in half, handing the canvas bare
  // heads and headless bodies. The URL carries the sheet's own fingerprint to
  // make that impossible: re-cut the guys and it is a URL nothing has cached.
  const stamp = createHash("sha256").update(shipped).digest("hex").slice(0, 8);

  const manifest = {
    note: `Generated by scripts/content/make-guys-sprites.mjs from ${SHEETS.map((s) => s.file).join(", ")} — do not hand-edit.`,
    sheet: `/guys/guys.webp?v=${stamp}`,
    cellWidth: Math.round(cellW * SHIP_SCALE),
    cellHeight: Math.round(cellH * SHIP_SCALE),
    columns: cols,
    count: cuts.length,
    // Where the ink actually sits inside its cell, [x, y, w, h] in shipped
    // pixels. Cells are all the size of the biggest figure and each guy is
    // centred in his own, so a short one is adrift in a lot of nothing —
    // anything that has to stand him on a line (the Party portrait does)
    // needs to know where his feet are.
    cells: cuts.map((c) => [
      Math.round(Math.round((cellW - c.w) / 2) * SHIP_SCALE),
      Math.round(Math.round((cellH - c.h) / 2) * SHIP_SCALE),
      Math.round(c.w * SHIP_SCALE),
      Math.round(c.h * SHIP_SCALE),
    ]),
  };
  // One cell per line — a couple of hundred four-number arrays exploded over
  // six lines each is not a file anybody wants to scroll past.
  const json = JSON.stringify(manifest, null, 2).replace(
    /\[\s+(\d+),\s+(\d+),\s+(\d+),\s+(\d+)\s+\]/g,
    "[$1, $2, $3, $4]",
  );
  await writeFile(MANIFEST_OUT, `${json}\n`);

  console.log(
    `${cuts.length} guys → ${SHEET_OUT} (${shipW}×${shipH}, cell ${Math.round(cellW * SHIP_SCALE)}×${Math.round(cellH * SHIP_SCALE)})`,
  );

  if (debug) {
    const contact = process.env.DEBUG_OUT ?? "guys-contact.png";
    await sharp(SHEET_OUT)
      .flatten({ background: "#ffffff" })
      .png()
      .toFile(contact);
    console.log(`contact sheet → ${contact}`);
  }
}

/**
 * Finds every whole figure on one photographed sheet and cuts it out, returning
 * a tight RGBA buffer per figure — the ink only, on nothing.
 */
async function cutSheet({ file, crop }) {
  const base = sharp(file).rotate().extract(crop).resize({ width: WORK_WIDTH }).greyscale();
  const { data: grey, info } = await base.clone().raw().toBuffer({ resolveWithObject: true });
  const { width, height } = info;

  // The paper is lit unevenly — brighter top right than bottom left — so "ink"
  // is judged against the local paper tone rather than one global threshold.
  const { data: paper } = await base.clone().blur(24).raw().toBuffer({ resolveWithObject: true });

  const ink = new Uint8Array(width * height);
  for (let i = 0; i < ink.length; i += 1) {
    ink[i] = paper[i] - grey[i] > INK ? 1 : 0;
  }

  // A figure is a handful of separate brush strokes — head clear of the body,
  // legs clear of both — so labelling the ink as it stands cuts every guy into
  // pieces. Fattening the mask first closes those gaps without closing the much
  // wider ones between neighbours; the cut-out still uses the original ink.
  const merged = dilate(ink, width, height, 4);
  const blobs = label(merged, width, height);
  attachHeads(blobs);

  const figures = splitPairs(pickFigures(blobs, width, height), blobs, ink, width);

  return figures.map((figure) => {
    const pixels = Buffer.alloc(figure.w * figure.h * 4);
    for (let y = 0; y < figure.h; y += 1) {
      for (let x = 0; x < figure.w; x += 1) {
        const src = (figure.y + y) * width + (figure.x + x);
        // Only this figure's own pixels: a neighbour leaning into the same box
        // stays behind.
        if (blobs.ids[src] !== figure.id) continue;
        // Alpha carries the brush texture — these are painted, not printed, and
        // a hard cut-out loses the dry-brush edges.
        const darkness = Math.max(0, Math.min(255, Math.round(((paper[src] - grey[src]) / 120) * 255)));
        if (darkness < 12) continue;
        const dst = (y * figure.w + x) * 4;
        pixels[dst] = 12;
        pixels[dst + 1] = 12;
        pixels[dst + 2] = 16;
        pixels[dst + 3] = darkness;
      }
    }
    return { w: figure.w, h: figure.h, pixels };
  });
}

/**
 * Two guys painted shoulder to shoulder come out as one blob, and a cell with
 * two figures in it is worse than no cell at all. Their ink never actually
 * touches, though — there is a column of bare paper between them, and only the
 * fattened mask bridges it — so a blob much wider than its neighbours is cut
 * down the empty column nearest its middle and each half measured afresh. One
 * that has no such column is a real overlap, and is dropped rather than shipped
 * as a two-headed guy.
 */
function splitPairs(figures, blobs, ink, width) {
  if (figures.length === 0) return figures;
  const widths = figures.map((f) => f.w).sort((a, b) => a - b);
  const median = widths[Math.floor(widths.length / 2)];

  const out = [];
  for (const figure of figures) {
    if (figure.w <= median * 1.45) {
      out.push(figure);
      continue;
    }

    // Bare columns, counting this blob's own ink only — a neighbour's arm
    // reaching into the same box is not what holds these two together.
    const bare = [];
    for (let x = 0; x < figure.w; x += 1) {
      let any = false;
      for (let y = 0; y < figure.h && !any; y += 1) {
        const p = (figure.y + y) * width + (figure.x + x);
        if (ink[p] === 1 && blobs.ids[p] === figure.id) any = true;
      }
      if (!any) bare.push(x);
    }

    // The gap between two figures is the one nearest the middle; the others are
    // the bare paper between a figure's own body and its arm.
    const middle = (figure.w - 1) / 2;
    const at = bare
      .filter((x) => x > figure.w * 0.25 && x < figure.w * 0.75)
      .sort((a, b) => Math.abs(a - middle) - Math.abs(b - middle))[0];
    const halves =
      at === undefined
        ? []
        : [measure(blobs, figure, 0, at - 1, width), measure(blobs, figure, at + 1, figure.w - 1, width)];
    // Both halves have to look like a figure in their own right, or the cut was
    // in the wrong place.
    if (halves.every((half) => half && half.w >= median * 0.5 && half.h > half.w)) out.push(...halves);
  }
  return out;
}

/** The box around one stretch of a blob's columns, `from` to `to` inclusive. */
function measure(blobs, figure, from, to, width) {
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -1;
  let maxY = -1;
  let area = 0;
  for (let y = 0; y < figure.h; y += 1) {
    for (let x = from; x <= to; x += 1) {
      if (blobs.ids[(figure.y + y) * width + (figure.x + x)] !== figure.id) continue;
      area += 1;
      if (x < minX) minX = x;
      if (x > maxX) maxX = x;
      if (y < minY) minY = y;
      if (y > maxY) maxY = y;
    }
  }
  if (maxX < 0) return null;
  return {
    id: figure.id,
    x: figure.x + minX,
    y: figure.y + minY,
    w: maxX - minX + 1,
    h: maxY - minY + 1,
    area,
  };
}

/** Grows the mask by `r` pixels in each direction, one axis at a time. */
function dilate(mask, width, height, r) {
  const pass = new Uint8Array(mask.length);
  for (let y = 0; y < height; y += 1) {
    const row = y * width;
    for (let x = 0; x < width; x += 1) {
      if (mask[row + x] === 0) continue;
      const from = Math.max(0, x - r);
      const to = Math.min(width - 1, x + r);
      for (let nx = from; nx <= to; nx += 1) pass[row + nx] = 1;
    }
  }
  const out = new Uint8Array(mask.length);
  for (let y = 0; y < height; y += 1) {
    const row = y * width;
    for (let x = 0; x < width; x += 1) {
      if (pass[row + x] === 0) continue;
      const from = Math.max(0, y - r);
      const to = Math.min(height - 1, y + r);
      for (let ny = from; ny <= to; ny += 1) out[ny * width + x] = 1;
    }
  }
  return out;
}

/** Flood-fills the ink mask into numbered blobs, with each blob's bounding box. */
function label(ink, width, height) {
  const ids = new Int32Array(width * height).fill(-1);
  const boxes = [];
  const stack = new Int32Array(width * height);

  for (let start = 0; start < ink.length; start += 1) {
    if (ink[start] === 0 || ids[start] !== -1) continue;
    const id = boxes.length;
    let top = 0;
    stack[top++] = start;
    ids[start] = id;
    let minX = width;
    let minY = height;
    let maxX = 0;
    let maxY = 0;
    let area = 0;

    while (top > 0) {
      const p = stack[--top];
      const x = p % width;
      const y = (p - x) / width;
      area += 1;
      if (x < minX) minX = x;
      if (x > maxX) maxX = x;
      if (y < minY) minY = y;
      if (y > maxY) maxY = y;

      // Eight-way: a dry brush leaves strokes that only touch at the corners.
      for (let dy = -1; dy <= 1; dy += 1) {
        for (let dx = -1; dx <= 1; dx += 1) {
          const nx = x + dx;
          const ny = y + dy;
          if (nx < 0 || ny < 0 || nx >= width || ny >= height) continue;
          const n = ny * width + nx;
          if (ink[n] === 0 || ids[n] !== -1) continue;
          ids[n] = id;
          stack[top++] = n;
        }
      }
    }

    boxes.push({ id, x: minX, y: minY, w: maxX - minX + 1, h: maxY - minY + 1, area });
  }

  return { ids, boxes };
}

/** The typical figure height, used to judge everything else against. */
function medianHeight(boxes) {
  const heights = boxes
    .filter((b) => b.h >= 12 && b.area >= 60)
    .map((b) => b.h)
    .sort((a, b) => a - b);
  return heights.length === 0 ? 0 : heights[Math.floor(heights.length / 2)];
}

/**
 * Some heads are painted far enough clear of the shoulders that the dilation
 * never reaches them, and they label as a blob of their own — the figure comes
 * out decapitated. Dilating wider would catch them, but it also starts welding
 * neighbours together, so instead: a small round blob sitting just above a
 * body-sized one and inside its shoulders is that body's head. Merge it back in.
 * Mutates `blobs` — head pixels take the body's id and the body's box grows to
 * cover them.
 */
function attachHeads(blobs) {
  const { ids, boxes } = blobs;
  const median = medianHeight(boxes);
  if (median === 0) return;

  const bodies = boxes.filter((b) => b.h >= median * 0.5);
  // A head: a good fraction of a figure tall, roughly as wide as it is tall,
  // and solid. The stray dots and splashes on the sheet are far smaller.
  const heads = boxes.filter(
    (b) =>
      b.h >= median * 0.12 &&
      b.h <= median * 0.5 &&
      b.w <= b.h * 1.8 &&
      b.h <= b.w * 1.8 &&
      b.area >= b.w * b.h * 0.6,
  );

  const taken = new Set();
  const remap = new Map();
  for (const head of heads) {
    const cx = head.x + head.w / 2;
    let best = null;
    let bestGap = Infinity;
    for (const body of bodies) {
      if (taken.has(body.id)) continue;
      // Just above, allowing a little overlap where a neck stroke reaches down.
      const gap = body.y - (head.y + head.h);
      if (gap < -median * 0.06 || gap > median * 0.1) continue;
      if (cx <= body.x || cx >= body.x + body.w) continue;
      if (head.w > body.w * 0.95) continue;
      if (gap < bestGap) {
        best = body;
        bestGap = gap;
      }
    }
    if (!best) continue;
    taken.add(best.id);
    remap.set(head.id, best.id);
    const right = Math.max(best.x + best.w, head.x + head.w);
    const bottom = Math.max(best.y + best.h, head.y + head.h);
    best.x = Math.min(best.x, head.x);
    best.y = Math.min(best.y, head.y);
    best.w = right - best.x;
    best.h = bottom - best.y;
    best.area += head.area;
  }
  if (remap.size === 0) return;

  for (let i = 0; i < ids.length; i += 1) {
    const to = remap.get(ids[i]);
    if (to !== undefined) ids[i] = to;
  }
  blobs.boxes = boxes.filter((b) => !remap.has(b.id));
}

/**
 * Keeps the blobs that are actually one whole figure: about as tall as the
 * typical one, taller than wide, solid enough not to be a smudge, and clear of
 * the crop edges where a figure may be cut in half.
 */
function pickFigures({ boxes }, width, height) {
  const tall = boxes.filter((b) => b.h >= 12 && b.area >= 60);
  if (tall.length === 0) return [];
  const median = medianHeight(boxes);

  return tall
    .filter((b) => {
      if (b.x <= 1 || b.y <= 1 || b.x + b.w >= width - 1 || b.y + b.h >= height - 1) return false;
      if (b.h < median * 0.62 || b.h > median * 1.45) return false;
      if (b.w > b.h * 0.95) return false;
      // A figure fills a good part of its box; a stray splash or two strokes
      // that happen to touch do not.
      if (b.area < b.w * b.h * 0.22) return false;
      return true;
    })
    .sort((a, b) => b.area - a.area);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
